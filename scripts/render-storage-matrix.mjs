/**
 * Render the storage-capability matrix from features.yaml.
 *
 * features.yaml is the single source of truth: each `adapters[]` entry declares
 * `capabilities: { record, vault }`. This script renders that into a
 * human-readable table at docs/subsystems/storage-capability-matrix.md.
 *
 *   record = per-record KV store   (NoydbStore: get/put/list)
 *   vault  = whole-vault bundle    (NoydbBundleStore: readBundle/writeBundle/listBundles)
 *
 * Usage:
 *   node scripts/render-storage-matrix.mjs           # write the doc
 *   node scripts/render-storage-matrix.mjs --check   # exit 1 if the doc is stale (CI)
 *
 * Exits 0 on success; 1 in --check mode when the rendered output differs.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'docs/subsystems/storage-capability-matrix.md')

const reg = yaml.load(readFileSync(resolve(ROOT, 'features.yaml'), 'utf8'))
const adapters = [...(reg.adapters ?? [])].sort((a, b) => a.id.localeCompare(b.id))

const yes = '✅'
const no = '❌'
const cell = (b) => (b ? yes : no)
const casCell = (a) => (a.capabilities?.vault && !a.capabilities?.record ? 'n/a' : a.cas_atomic ? yes : no)

const rows = adapters.map((a) => {
  const c = a.capabilities ?? {}
  return `| \`${a.id}\` | ${cell(c.record)} | ${cell(c.vault)} | ${casCell(a)} | ${a.use_case} | ${a.status} |`
})

const recordCount = adapters.filter((a) => a.capabilities?.record).length
const vaultCount = adapters.filter((a) => a.capabilities?.vault).length
const bothCount = adapters.filter((a) => a.capabilities?.record && a.capabilities?.vault).length

const body = `<!-- GENERATED by scripts/render-storage-matrix.mjs from features.yaml — do not edit by hand. -->
# Storage capability matrix

Which \`to-*\` adapter exposes which store shape. Generated from \`features.yaml\`
(\`adapters[].capabilities\`) — the single source of truth.

- **record** — per-record key-value store (\`NoydbStore\`: \`get\` / \`put\` / \`list\` / \`loadAll\`). The default shape for databases and object stores.
- **vault** — whole-vault bundle store (\`NoydbBundleStore\`: \`readBundle\` / \`writeBundle\` / \`listBundles\`). One encrypted \`.noydb\` blob per vault; the destination for \`withSnapshots()\` and bundle-mode sync.

A backend may expose **both** (e.g. \`@noy-db/to-aws-s3\` ships \`s3()\` for records
and \`s3Bundle()\` for whole-vault bundles). \`casAtomic\` is shown as \`n/a\` for
vault-only stores (concurrency there is per-bundle OCC, not per-record CAS).

| Adapter | record | vault | casAtomic | Use case | Status |
|---|:--:|:--:|:--:|---|---|
${rows.join('\n')}

**Totals:** ${adapters.length} adapters — ${recordCount} record-capable, ${vaultCount} vault-capable (${bothCount} both).
`

const check = process.argv.includes('--check')
if (check) {
  const current = (() => { try { return readFileSync(OUT, 'utf8') } catch { return '' } })()
  if (current !== body) {
    console.error('✗ storage-capability-matrix.md is stale. Run: node scripts/render-storage-matrix.mjs')
    process.exit(1)
  }
  console.log('✓ storage-capability-matrix.md is up to date')
} else {
  writeFileSync(OUT, body)
  console.log(`✓ wrote ${OUT.replace(ROOT + '/', '')} (${adapters.length} adapters)`)
}
